"""RH-04 V2 — CPU-portable, *criterion-declared* two-parameter calibration fit.

Status: **candidate / research-only**. Nothing in this module is wired into a
production default, the canonical V1 fixture, the canonical comparator, the
shipped workflow files or any scoring path. It exists so that a future V2
reference pack can be generated by an algorithm whose numbers do not depend on
the host CPU's dynamic-architecture BLAS dispatch.

Why this module exists
----------------------
The frozen V1 pack (``research/intake/fixtures/offline_io.v1.json``, digest
``0307b396…``) is a faithful record of one specific binary64 evaluation order
produced by SciPy's L-BFGS-B under a ``SkylakeX`` OpenBLAS kernel. Re-measured
evidence (``docs/rh04-issue132-acceptance-decision.md`` §1.2/§1.4) shows the
replay is exact only where SciPy's *resident* kernel is ``SkylakeX``, and drifts
by 1 ULP elsewhere. Two properties of that reference make it unfit as a
portable acceptance contract:

1. It is a *stopping* artifact, not an optimum (§2.3). Any solver that
   converges harder necessarily disagrees with it.
2. The fit enters through BLAS ``ddot_``/``daxpy_``/``dtrsl`` calls whose
   accumulation order is chosen at run time by the resident kernel.

The existing opt-in ``deterministic_portable_newton`` solver removes (2) but
cannot serve as a V2 reference. Measured defects:

* **Unreachable criterion.** Its only convergence test is a float64 KKT
  residual ``<= 1e-10``. In float64 the residual of a genuinely converged
  2-parameter fit bottoms out near ``1.3e-10`` on a real 64-row fold (the sum of
  64 rounded ``p_i - y_i`` terms cannot resolve further), so the solver loops
  until its iteration budget is exhausted and raises. On real data that is a
  false negative, not a non-convergence.
* **Implementation-property dependence.** Whether it stops by convergence or by
  budget exhaustion is decided by last-ULP rounding of float64 iterates.

What V2 does instead
--------------------
The same objective and the same box-constrained KKT criterion are evaluated in
**software-defined decimal arithmetic** (:mod:`decimal`, 40 significant digits,
``ROUND_HALF_EVEN``). Every arithmetic decision is therefore a property of the
declared algorithm and its declared precision — not of the host CPU, the BLAS
build, the libm build, or the order in which a SIMD kernel reduces a vector.

Two deliberate deviations from a textbook projected-Newton solver, each forced
by a *measured* failure on a real repository cohort (both are documented at the
line where they are implemented):

* **Exact 1-D line minimisation** along each step instead of Armijo backtracking.
  Armijo compares objective *values*; at 40 digits the difference between
  ``f(x)`` and ``f(x + t*d)`` for small ``t`` is below the resolution of the
  representation, so a perfectly good tiny step can fail the test. A convex
  two-parameter problem admits an exact, tolerance-free golden-section search.
* **Active-set pinning only by the box cap**, plus a projected-gradient fallback
  when the coupled Newton step has zero feasible length.

The declared criterion is ``max_i kkt_i <= 1e-16``. It is *reachable*: the
measured residual at the decimal optimum of the repository cohorts is
``1e-18…1e-17``. It is also ~6 orders tighter than the float64 floor (``1e-10``)
that made the float64 solver loop — that is precisely why it is evaluated in
decimal arithmetic.

Returned parameters are quantised **once**, at the end, by ``float(Decimal)``,
which is correctly rounded and therefore reproducible on every IEEE-754
binary64 platform.

Scope limits — read before quoting any number from this module
--------------------------------------------------------------
* ``decimal`` arithmetic is portable *software* arithmetic, but its operational
  guarantees are those of CPython's ``_decimal`` (MPDEC). It is not IEEE-754
  binary arithmetic; no claim is made that it matches an independent decimal
  implementation bit for bit.
* Inputs are binary64 (the OOF probabilities and their clipped logits);
  conversion to ``Decimal`` is exact, so nothing is lost at the boundary.
* No claim is made about downstream numerics. ``scipy.special.expit`` (the map
  from calibrated log-odds to the research score) and sklearn's BLAS
  ``decision_function`` are separate code paths; see
  :mod:`research.intake.rh04_v2_portability_audit` for what was measured about
  them. The audit's finding is that the linear family's ``gemv`` is *not*
  portable, so a V2 pack cannot be made 29/29 portable by replacing the
  calibrator alone.
* Engineering reproducibility only: no clinical validity, no model equivalence,
  no change to any scientific claim.
"""

from __future__ import annotations

import math
from decimal import Decimal, ROUND_HALF_EVEN, localcontext
from typing import Any, Final, Sequence

import numpy as np

from ai.errors import CalibrationIntegrityError

# --- Declared, versioned algorithm constants ------------------------------- #
# Bumping ANY of these changes the reference and therefore requires a new
# pack/digest version. They are part of the contract, not tunables.
V2_FIT_PROTOCOL_ID: Final[str] = "rh04.v2.decimal-reference-fit/v2"
V2_FIT_DECIMAL_PRECISION: Final[int] = 40
V2_FIT_KKT_TOLERANCE_EXPONENT: Final[int] = -16
V2_FIT_KKT_TOLERANCE: Final[Decimal] = Decimal("1e-16")
# Measured at the decimal optimum of the repository cohorts; recorded so a
# reader can see the declared tolerance is reachable rather than aspirational.
V2_FIT_MEASURED_KKT_FLOOR: Final[str] = "1e-18"
# Float64 KKT residuals cannot resolve below this order for these cohorts; the
# declared criterion is ~6 orders below it on purpose.
V2_FLOAT64_KKT_FLOOR_ORDER: Final[int] = -10
V2_FIT_MAX_ITERATIONS: Final[int] = 200
V2_FIT_LINE_SEARCH_ITERATIONS: Final[int] = 140
V2_FIT_L2_ANCHOR: Final[Decimal] = Decimal("1e-3")
# Exactly the production bounds, so both solvers optimise the same constrained
# problem and calibration semantics never drift between them.
V2_FIT_LOWER: Final[tuple[Decimal, Decimal]] = (Decimal(-15), Decimal("0.01"))
V2_FIT_UPPER: Final[tuple[Decimal, Decimal]] = (Decimal(15), Decimal(15))
V2_FIT_MIN_SAMPLES: Final[int] = 8
# Relative golden-section ratio, declared as a string so the constant itself is
# not a float: (sqrt(5) - 1) / 2.
_GOLDEN_RATIO = (Decimal(5).sqrt() - 1) / 2


def declared_protocol() -> dict[str, Any]:
    """Machine-readable declaration of the reference algorithm and criterion.

    Written into the V2 pack/provenance so a future reader can tell *which*
    reference a value came from without reading this module.
    """
    return {
        "protocol_id": V2_FIT_PROTOCOL_ID,
        "arithmetic": "python_decimal_software",
        "decimal_precision_significant_digits": V2_FIT_DECIMAL_PRECISION,
        "rounding": "ROUND_HALF_EVEN",
        "convergence_criterion": "box_kkt_residual_max_component",
        "convergence_tolerance": f"1e{V2_FIT_KKT_TOLERANCE_EXPONENT}",
        "criterion_is_reachable": True,
        "measured_kkt_floor_at_optimum": V2_FIT_MEASURED_KKT_FLOOR,
        "criterion_reachability_note": (
            "Measured residual at the decimal optimum is 1e-18..1e-17 on the "
            "repository cohorts, so 1e-16 is reachable with margin. The float64 "
            "residual floor for the same cohorts is ~1e-10, so this criterion is "
            "NOT reachable in float64 — which is exactly why it is evaluated in "
            "decimal arithmetic."
        ),
        "max_iterations": V2_FIT_MAX_ITERATIONS,
        "line_search": "exact_golden_section_1d_140_iterations",
        "l2_anchor": str(V2_FIT_L2_ANCHOR),
        "lower_bounds": [str(value) for value in V2_FIT_LOWER],
        "upper_bounds": [str(value) for value in V2_FIT_UPPER],
        "objective": "mean(softplus(eta)-y*eta)+0.5*l2*(a^2+(b-1)^2)",
        "final_conversion": "correctly_rounded_decimal_to_binary64",
        "host_dependent_operations": [],
        "blas_calls": 0,
        "libm_calls": 0,
        "python_float_transcendentals_used": 0,
    }


def as_decimal(value: Any) -> Decimal:
    """Exact Decimal view of a binary64 value (or pass a Decimal/str through)."""
    if isinstance(value, Decimal):
        return value
    if isinstance(value, str):
        return Decimal(value)
    return Decimal(float(value))


def _validate(y: np.ndarray, logits: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    y_array = np.asarray(y, dtype=np.float64)
    logit_array = np.asarray(logits, dtype=np.float64)
    if y_array.ndim != 1 or y_array.shape != logit_array.shape:
        raise CalibrationIntegrityError(
            "invalid_v2_fit_inputs",
            "V2 reference fit requires aligned 1-D arrays.",
        )
    if y_array.size < V2_FIT_MIN_SAMPLES:
        raise CalibrationIntegrityError(
            "invalid_v2_fit_inputs",
            f"V2 reference fit requires >= {V2_FIT_MIN_SAMPLES} observations.",
        )
    if not np.isfinite(y_array).all() or not np.isfinite(logit_array).all():
        raise CalibrationIntegrityError(
            "invalid_v2_fit_inputs",
            "V2 reference fit requires finite inputs.",
        )
    if set(np.unique(y_array).tolist()) != {0.0, 1.0}:
        raise CalibrationIntegrityError(
            "invalid_v2_fit_inputs",
            "V2 reference fit requires both target classes (0.0 and 1.0).",
        )
    return y_array, logit_array


def _softplus(eta: Decimal) -> Decimal:
    """Overflow-free ``log(1 + exp(eta))`` in decimal arithmetic."""
    one = Decimal(1)
    if eta >= 0:
        return eta + (one + (-eta).exp()).ln()
    return (one + eta.exp()).ln()


def _sigmoid(eta: Decimal) -> Decimal:
    """Overflow-free logistic sigmoid in decimal arithmetic."""
    one = Decimal(1)
    if eta >= 0:
        return one / (one + (-eta).exp())
    e = eta.exp()
    return e / (one + e)


def _face(x: Decimal, low: Decimal, high: Decimal) -> str:
    """Exact box-face membership (never epsilon-based).

    The iterates reach a face either exactly or by the 1-D line search landing
    there; an epsilon band would misclassify near-but-interior points as faces
    and silently disable a legitimate descent direction.
    """
    if x <= low:
        return "lower"
    if x >= high:
        return "upper"
    return "interior"


def _kkt_residual(
    a: Decimal,
    b: Decimal,
    grad_a: Decimal,
    grad_b: Decimal,
    lower: tuple[Decimal, Decimal],
    upper: tuple[Decimal, Decimal],
) -> Decimal:
    """Box-constrained KKT residual: max of the per-component residuals."""
    zero = Decimal(0)
    status_a = _face(a, lower[0], upper[0])
    status_b = _face(b, lower[1], upper[1])
    if status_a == "lower":
        resid_a = max(zero, -grad_a)
    elif status_a == "upper":
        resid_a = max(zero, grad_a)
    else:
        resid_a = abs(grad_a)
    if status_b == "lower":
        resid_b = max(zero, -grad_b)
    elif status_b == "upper":
        resid_b = max(zero, grad_b)
    else:
        resid_b = abs(grad_b)
    return max(resid_a, resid_b)


def _feasible_step_length(
    a: Decimal,
    b: Decimal,
    step_a: Decimal,
    step_b: Decimal,
    low_a: Decimal,
    low_b: Decimal,
    high_a: Decimal,
    high_b: Decimal,
) -> Decimal:
    """Largest t in [0, 1] keeping (a + t*step_a, b + t*step_b) inside the box."""
    limit = Decimal(1)
    if step_a > 0:
        limit = min(limit, (high_a - a) / step_a)
    elif step_a < 0:
        limit = min(limit, (low_a - a) / step_a)
    if step_b > 0:
        limit = min(limit, (high_b - b) / step_b)
    elif step_b < 0:
        limit = min(limit, (low_b - b) / step_b)
    return max(Decimal(0), limit)


def _newton_step_on_free_block(
    free_a: bool,
    free_b: bool,
    grad_a: Decimal,
    grad_b: Decimal,
    hess_a: Decimal,
    hess_ab: Decimal,
    hess_b: Decimal,
) -> tuple[Decimal, Decimal]:
    """Newton step restricted to the free components (pinned ones stay fixed)."""
    zero = Decimal(0)
    if free_a and free_b:
        determinant = hess_a * hess_b - hess_ab * hess_ab
        if not (determinant.is_finite() and determinant > 0):
            raise CalibrationIntegrityError(
                "calibration_solver_degenerate_hessian",
                "V2 reference fit encountered a non-positive Hessian determinant.",
            )
        return (
            (-grad_a * hess_b + grad_b * hess_ab) / determinant,
            (-grad_b * hess_a + grad_a * hess_ab) / determinant,
        )
    if free_a:
        if not (hess_a.is_finite() and hess_a > 0):
            raise CalibrationIntegrityError(
                "calibration_solver_degenerate_hessian",
                "V2 reference fit encountered a non-positive curvature.",
            )
        return -grad_a / hess_a, zero
    if not (hess_b.is_finite() and hess_b > 0):
        raise CalibrationIntegrityError(
            "calibration_solver_degenerate_hessian",
            "V2 reference fit encountered a non-positive curvature.",
        )
    return zero, -grad_b / hess_b


def decimal_logistic_fit(
    y: np.ndarray,
    logits: np.ndarray,
    *,
    l2_anchor: Decimal = V2_FIT_L2_ANCHOR,
    lower: tuple[Decimal, Decimal] = V2_FIT_LOWER,
    upper: tuple[Decimal, Decimal] = V2_FIT_UPPER,
    max_iterations: int = V2_FIT_MAX_ITERATIONS,
    kkt_tolerance: Decimal = V2_FIT_KKT_TOLERANCE,
    decimal_precision: int = V2_FIT_DECIMAL_PRECISION,
) -> tuple[float, float]:
    """Fit the two-parameter L2-anchored logistic calibration in decimal arithmetic.

    Returns binary64 parameters obtained by one correctly-rounded conversion per
    parameter at the end. Raises :class:`CalibrationIntegrityError` (fail closed)
    if the declared criterion is not met within the declared iteration budget —
    the caller must never receive unconverged parameters.

    The function is a deterministic, host-independent function of its binary64
    inputs and the declared constants.
    """
    y_array, logit_array = _validate(y, logits)
    if not isinstance(decimal_precision, int) or decimal_precision < 28:
        raise CalibrationIntegrityError(
            "invalid_v2_fit_controls",
            "decimal_precision must be an integer >= 28 (the module default).",
        )
    if not isinstance(max_iterations, int) or max_iterations < 1:
        raise CalibrationIntegrityError(
            "invalid_v2_fit_controls",
            "max_iterations must be a positive integer.",
        )
    if not (Decimal(0) < kkt_tolerance < Decimal(1)):
        raise CalibrationIntegrityError(
            "invalid_v2_fit_controls",
            "kkt_tolerance must lie strictly inside (0, 1).",
        )
    if not (
        isinstance(l2_anchor, Decimal) and l2_anchor.is_finite() and l2_anchor > 0
    ):
        raise CalibrationIntegrityError(
            "invalid_v2_fit_controls",
            "l2_anchor must be a finite positive Decimal.",
        )
    for low, high in (lower, upper):
        if not (isinstance(low, Decimal) and isinstance(high, Decimal)):
            raise CalibrationIntegrityError(
                "invalid_v2_fit_controls",
                "Bounds must be Decimals.",
            )

    with localcontext() as context:
        context.prec = decimal_precision
        context.rounding = ROUND_HALF_EVEN

        targets = [Decimal(float(value)) for value in y_array]
        features = [Decimal(float(value)) for value in logit_array]
        count = Decimal(len(targets))
        one = Decimal(1)
        low_a, low_b = lower
        high_a, high_b = upper

        def objective(a: Decimal, b: Decimal) -> Decimal:
            total = Decimal(0)
            for target, feature in zip(targets, features):
                eta = a + b * feature
                total += _softplus(eta) - target * eta
            return total / count + (l2_anchor / 2) * (a * a + (b - one) ** 2)

        def gradient(a: Decimal, b: Decimal) -> tuple[Decimal, Decimal]:
            total = Decimal(0)
            total_features = Decimal(0)
            for target, feature in zip(targets, features):
                diff = _sigmoid(a + b * feature) - target
                total += diff
                total_features += diff * feature
            return (
                total / count + l2_anchor * a,
                total_features / count + l2_anchor * (b - one),
            )

        def hessian(a: Decimal, b: Decimal) -> tuple[Decimal, Decimal, Decimal]:
            sum_q = Decimal(0)
            sum_q_feature = Decimal(0)
            sum_q_feature2 = Decimal(0)
            for feature in features:
                probability = _sigmoid(a + b * feature)
                curvature = probability * (one - probability)
                sum_q += curvature
                sum_q_feature += curvature * feature
                sum_q_feature2 += curvature * feature * feature
            return (
                sum_q / count + l2_anchor,
                sum_q_feature / count,
                sum_q_feature2 / count + l2_anchor,
            )

        def exact_line_minimiser(
            a: Decimal, b: Decimal, step_a: Decimal, step_b: Decimal, cap: Decimal
        ) -> Decimal:
            """Golden-section minimisation of phi(t) = f(a + t*step_a, b + t*step_b).

            Convex in t, so the 1-D minimiser is well defined; the grid is
            deterministic and the comparison is an exact decimal comparison, so
            no tolerance is involved anywhere in this search.
            """
            lo, hi = Decimal(0), cap
            for _ in range(V2_FIT_LINE_SEARCH_ITERATIONS):
                probe_1 = hi - _GOLDEN_RATIO * (hi - lo)
                probe_2 = lo + _GOLDEN_RATIO * (hi - lo)
                value_1 = objective(a + probe_1 * step_a, b + probe_1 * step_b)
                value_2 = objective(a + probe_2 * step_a, b + probe_2 * step_b)
                if value_1 <= value_2:
                    hi = probe_2
                else:
                    lo = probe_1
            candidates = (Decimal(0), lo, hi, (lo + hi) / 2, cap)
            return min(
                candidates,
                key=lambda t: objective(a + t * step_a, b + t * step_b),
            )

        a, b = Decimal(0), one
        for _iteration in range(max_iterations):
            grad_a, grad_b = gradient(a, b)
            if _kkt_residual(a, b, grad_a, grad_b, lower, upper) <= kkt_tolerance:
                return float(a), float(b)

            status_a = _face(a, low_a, high_a)
            status_b = _face(b, low_b, high_b)
            # A component on a face is a candidate only when an inward step
            # reduces the objective; an outward-pointing gradient means the face
            # is the constrained optimum for that component.
            free_a = (
                grad_a < 0
                if status_a == "lower"
                else (grad_a > 0 if status_a == "upper" else True)
            )
            free_b = (
                grad_b < 0
                if status_b == "lower"
                else (grad_b > 0 if status_b == "upper" else True)
            )
            if not (free_a or free_b):
                residual = _kkt_residual(a, b, grad_a, grad_b, lower, upper)
                raise CalibrationIntegrityError(
                    "calibration_solver_did_not_converge",
                    "V2 reference fit has no interior free direction while the "
                    f"KKT residual {float(residual):.3e} exceeds the declared "
                    f"tolerance {float(kkt_tolerance):.3e}.",
                )

            hess_a, hess_ab, hess_b = hessian(a, b)
            # Active set: pin a candidate only when it sits on a face AND its
            # Newton step points outward. Two re-solves suffice for two variables.
            for _resolve in range(3):
                step_a, step_b = _newton_step_on_free_block(
                    free_a, free_b, grad_a, grad_b, hess_a, hess_ab, hess_b
                )
                pinned_a = free_a and (
                    (status_a == "lower" and step_a < 0)
                    or (status_a == "upper" and step_a > 0)
                )
                pinned_b = free_b and (
                    (status_b == "lower" and step_b < 0)
                    or (status_b == "upper" and step_b > 0)
                )
                if not (pinned_a or pinned_b):
                    break
                free_a = free_a and not pinned_a
                free_b = free_b and not pinned_b
                if not (free_a or free_b):
                    break

            cap = _feasible_step_length(
                a, b, step_a, step_b, low_a, low_b, high_a, high_b
            )
            if cap == 0:
                # The coupled Newton step lands outside the box even though this
                # point is not on a face (measured on a real fold: cap ~1e-39).
                # Use the projected-gradient step instead; the exact line search
                # still has to certify a decrease, so nothing is accepted blindly.
                step_a = (-grad_a / hess_a) if free_a else Decimal(0)
                step_b = (-grad_b / hess_b) if free_b else Decimal(0)
                cap = _feasible_step_length(
                    a, b, step_a, step_b, low_a, low_b, high_a, high_b
                )
                if cap == 0:
                    residual = _kkt_residual(a, b, grad_a, grad_b, lower, upper)
                    raise CalibrationIntegrityError(
                        "calibration_solver_did_not_converge",
                        "V2 reference fit has no feasible movement from this "
                        f"point (KKT residual {float(residual):.3e}).",
                    )
            if not (free_a or free_b):
                # Both candidates were pinned by the active set: the point is the
                # box optimum for the current face pattern, but the exact KKT
                # test has not certified it. That can only happen when the
                # residual sits at representation scale, so fail closed rather
                # than silently accepting.
                residual = _kkt_residual(a, b, grad_a, grad_b, lower, upper)
                raise CalibrationIntegrityError(
                    "calibration_solver_did_not_converge",
                    "V2 reference fit pinned every free component while the KKT "
                    f"residual {float(residual):.3e} exceeds the declared "
                    f"tolerance {float(kkt_tolerance):.3e}.",
                )

            t = exact_line_minimiser(a, b, step_a, step_b, cap)
            if t == 0:
                residual = _kkt_residual(a, b, grad_a, grad_b, lower, upper)
                raise CalibrationIntegrityError(
                    "calibration_solver_did_not_converge",
                    "V2 reference fit found no improving step along its Newton "
                    f"direction (KKT residual {float(residual):.3e}).",
                )
            a = min(max(a + t * step_a, low_a), high_a)
            b = min(max(b + t * step_b, low_b), high_b)

        raise CalibrationIntegrityError(
            "calibration_solver_did_not_converge",
            "V2 reference fit did not reach the declared KKT tolerance within "
            f"{max_iterations} iterations.",
        )


def fit_is_host_independent(y: np.ndarray, logits: np.ndarray) -> bool:
    """Re-fit twice and confirm the binary64 result is identical.

    Determinism of a pure function is expected; the point is to make a
    regression (e.g. an accidental dependency on a float64 path) fail loudly
    instead of silently.
    """
    first = decimal_logistic_fit(y, logits)
    second = decimal_logistic_fit(y, logits)
    return math.isfinite(first[0]) and math.isfinite(first[1]) and first == second
