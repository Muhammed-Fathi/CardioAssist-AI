def _make_raw_76_record_from_14(
    rec_id: int,
    conv_14: Sequence[str],
) -> str:
    """Create a multi-line 76-token raw UCI-45 record matching the 14 conventional attributes."""
    tokens = ["0"] * 76
    tokens[0] = str(1000 + rec_id)  # #1 id (never exposed in reports)
    tokens[1] = str(2000 + rec_id)  # #2 ccf (never exposed in reports)
    for col_idx, (col_name, val_str) in enumerate(
        zip(
            ("age", "sex", "cp", "trestbps", "chol", "fbs", "restecg", "thalach", "exang", "oldpeak", "slope", "ca", "thal", "num"),
            conv_14,
        )
    ):
        pos_1based = UCI_45_RAW_TO_CONVENTIONAL_1BASED[col_name]
        raw_tok = "-9" if val_str == "?" else val_str
        tokens[pos_1based - 1] = raw_tok

    # Populate per-vessel fields (#59-#68) with discrete 1/2 codes or -9
    num_val = int(float(conv_14[13]))
    for v_idx in range(58, 68):
        tokens[v_idx] = "2" if (num_val > 0 and v_idx == 59) else "1"
    tokens[75] = "name"

    # Format as 8 lines per record (similar to UCI-45 multi-line layout)
    lines = [" ".join(tokens[i : i + 10]) for i in range(0, 76, 10)]
    return "\n".join(lines)


