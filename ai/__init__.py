"""End-to-end Track A CAD AI research pipeline (RESEARCH_ONLY, offline).

This package implements the reusable, synthetic-verified AI research components
planned in ``docs/research/AI_FIRST_COMPLETION_STRATEGY.md``:
- :mod:`ai.panels` — staged clinical & routine laboratory input contracts
  (reusing ``research.intake`` and ``research.uci412.feature_schema``).
- :mod:`ai.preprocessing` — fold-contained, lineage-preserving tabular
  preprocessing with deterministic JSON state export.
- :mod:`ai.calibration` — monotone logistic probability calibration (cross-fitted
  inner-OOF fold calibrators + development-OOF final calibrator), bootstrap CIs,
  prevalence-shift diagnostics, and descriptive outer-fold dispersion.
- :mod:`ai.explainability` — genuine, model-faithful Grouped Interventional
  LinearSHAP (exact on both ``raw_log_odds`` and ``calibrated_log_odds``) and
  Grouped Interventional TreeSHAP (exact on ``raw_model_probability``), plus
  explicit training-derivative privacy metadata on ``shap_background.json``.
- :mod:`ai.lime_quality` — generation-free LIME quality assessment: a
  registered acceptance policy, five machine-readable verdicts
  (ACCEPTABLE_LOCAL_APPROXIMATION / LOW_LOCAL_FIDELITY / UNSTABLE /
  UNVERIFIED_STABILITY / INVALID), per-criterion evidence and explicit
  "do not rely on these weights" guards.
- :mod:`ai.lime_explainability` — genuine tabular LIME: seeded binary-mask
  perturbations over validated clinical/laboratory fields, decoded-background
  marginal references, an exponential normalized-Hamming kernel, and a
  kernel-weighted ridge local surrogate fitted on actual estimator calls, with
  explicit explained-quantity/scale declarations, local-fidelity and
  seed-stability diagnostics, and hard resource ceilings. Explicitly a local
  approximation — never presented as exact Shapley attribution.
- :mod:`ai.training` — nested-CV selection, cross-fitted calibration evaluation,
  label-shuffle negative controls, frozen external-cohort evaluation primitive,
  and locally protected ``ExternalEvaluationLedger`` single-shot enforcement.
- :mod:`ai.packaging` — staging-directory atomic ``RESEARCH_ONLY`` bundle
  packaging, SHA-256 integrity checks, and ``HMAC-SHA256`` + ``trusted_local_root``
  authentication BEFORE any ``joblib.load``.
- :mod:`ai.inference` — offline ``ResearchCadPredictor`` returning explicitly
  separated raw/calibrated scores, descriptive fold dispersion, aligned SHAP
  attributions, and mandatory non-clinical limitations.
- :mod:`ai.research_registry` — immutable, versioned research model/route
  registry: which synthetic model entries exist, at what evidence level, which
  artifact kind and execution profile each one admits, and what a verified
  artifact actually supports (calibration, exact SHAP, certified LIME). Blocked,
  source-timing-unverified and locked-external-target entries are registered for
  contract inspection only and are never executable; real-patient artifacts are
  not registerable at all.
- :mod:`ai.research_facade` — one typed, offline, fail-closed inference facade
  over the registry and the existing route/panel/training/packaging/inference/
  explainability components. Returns explicit ``SYNTHETIC_RESULT`` / ``ABSTAIN``
  / ``UNAVAILABLE`` / ``ERROR`` results, reports calibration and SHAP/LIME only
  when the verified artifact actually supports them, and refuses unregistered
  identifiers, invalid records, forged synthetic provenance and untrusted
  bundles without ever echoing submitted content back.
- :mod:`ai.research_demo` — ``python -m ai.research_demo`` reproducible
  synthetic demonstration: one successful run plus the refusal matrix, with a
  machine-readable stage report and a canonical payload digest.
- :mod:`ai.execution` — locally protected, auditable real-data execution
  controller enforcing hash-bound human research authorization manifests,
  source-specific read-only adapters, prohibited feature rejection, and Windows
  workstation private storage.

Never imported by ``backend/app/``; ``MOCK_SYNTHETIC`` remains the sole active
FastAPI runtime provider while Gate PT (``P-3``) is closed.
"""
