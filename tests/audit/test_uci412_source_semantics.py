def _synthetic_workbook_rows(
    profiles: Sequence[dict[str, Any]] = _SYNTHETIC_PROFILES,
) -> list[list[Any]]:
    headers = get_uci_412_headers(include_bbb=True, include_arteries=False)
    base = build_synthetic_uci_412_rows(headers, include_arteries=False)
    assert len(base) == len(profiles), "Synthetic profile count must match the fixture row count."
    index = {name: position for position, name in enumerate(headers)}
    rows: list[list[Any]] = []
    for source_row, profile in zip(base, profiles):
        row = list(source_row)
        for column, value in profile.items():
            row[index[column]] = value
        rows.append(row)
    return rows


