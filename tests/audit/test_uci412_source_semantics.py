    assert coverage["registered_token_counts"] == {"N": 1, "No": 1, "Y": 1, "Yes": 1}
    assert coverage["observed_registered_tokens"] == ["N", "No", "Y", "Yes"]
    assert coverage["coding_coverage_status"] == COVERAGE_ALL_CELLS


