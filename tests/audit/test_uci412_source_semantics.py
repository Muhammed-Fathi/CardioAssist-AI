    assert census["records_with_any_missing_cell"] == 1
    assert census["records_with_any_unregistered_cell"] == 2
    assert sum(census["descriptor_count_distribution"].values()) == 1
    assert SENTINEL_UNREGISTERED_TOKEN not in json.dumps(census)


