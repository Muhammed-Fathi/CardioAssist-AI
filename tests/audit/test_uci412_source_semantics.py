def test_dictionary_must_be_a_clean_committed_repository_file(tmp_path: Path) -> None:
    """An unreviewed local vocabulary can never define the audit's coding checks."""
    repo = tmp_path / "synthetic_repo"
    relative = Path("research/uci412/schemas/uci412_feature_dictionary.v1.json")
    target = repo / relative
    target.parent.mkdir(parents=True)
    target.write_text('{"schema_id": "uci412_research_feature_dictionary"}\n', encoding="utf-8")

    def _git(*args: str) -> None:
        subprocess.run(
            [
                "git",
                "-c",
                "user.email=synthetic@example.invalid",
                "-c",
                "user.name=Synthetic Test",
                *args,
            ],
            cwd=str(repo),
            check=True,
            capture_output=True,
            text=True,
        )

    _git("init")
    # 1. Present but untracked -> fail closed.
    with pytest.raises(FormatValidationError, match="not tracked by Git"):
        load_registered_source_semantics(repo)

    # 2. Tracked and clean -> the committed-state guard passes.
    _git("add", str(relative))
    _git("commit", "-m", "synthetic dictionary")
    from research.audit.uci412_source_semantics import _verify_committed_repo_file

    assert _verify_committed_repo_file(repo, str(relative).replace("\\", "/")) == target.resolve()

    # 3. Tracked but locally modified -> fail closed.
    target.write_text('{"schema_id": "uci412_research_feature_dictionary", "dirty": true}\n', encoding="utf-8")
    with pytest.raises(FormatValidationError, match="uncommitted local modifications"):
        load_registered_source_semantics(repo)


