def test_classify_cell_is_exact_and_never_returns_unregistered_text() -> None:
    semantics = load_registered_source_semantics(REPO_ROOT)
    text_spec = semantics["columns"]["DLP"]
    numeric_spec = semantics["columns"]["Typical Chest Pain"]

    assert classify_cell(None, text_spec) == ("missing", "")
    assert classify_cell("Y", text_spec) == ("registered", "Y")
    assert classify_cell("Yes", text_spec) == ("registered", "Yes")
    # Whitespace is never stripped: a trimmed match could accept a different token.
    assert classify_cell("Y ", text_spec) == ("unregistered", "")
    assert classify_cell(0, text_spec) == ("unregistered", "")
    assert classify_cell(SENTINEL_UNREGISTERED_TOKEN, text_spec) == ("unregistered", "")
    assert classify_cell(True, text_spec) == ("unregistered", "")
    assert classify_cell(1.5, text_spec) == ("unregistered", "")
    assert classify_cell(float("nan"), text_spec) == ("unregistered", "")

    assert classify_cell(1, numeric_spec) == ("registered", "1")
    assert classify_cell(0.0, numeric_spec) == ("registered", "0")
    # The dictionary rejects the *strings* '0' and '1' for this column, so a
    # numeric-binary column must not silently accept them either.
    assert classify_cell("1", numeric_spec) == ("unregistered", "")
    assert classify_cell("0", numeric_spec) == ("unregistered", "")
    assert classify_cell("Y", numeric_spec) == ("unregistered", "")
    assert classify_cell(True, numeric_spec) == ("unregistered", "")
    assert classify_cell(2, numeric_spec) == ("unregistered", "")
    assert classify_cell(1.5, numeric_spec) == ("unregistered", "")
    # A text column must not accept numbers merely because '0'/'1' are tokens of
    # some other column's registered representation.
    assert classify_cell(1, text_spec) == ("unregistered", "")


