"""RH-04 Issue #132: NON-VOTING CI observation of the resident OpenBLAS kernels.

**This script is an observer, not a gate, and it always exits 0.**

It runs the merged read-only classifier
(``python -m research.intake.rh04_environment_class``) in a fresh process, and
writes a redacted, metadata-only block to ``$GITHUB_STEP_SUMMARY``.

Why a helper rather than the inline shell block in the specification
-------------------------------------------------------------------
The specification's inline ``case`` statement can map an exit code to a label,
but it cannot surface the resolved kernel identities, their identification
methods, or the fine-grained verdict into the step summary without parsing JSON
in shell. A shell step is also not unit-testable. This helper does the same job
in one reviewed place and enforces two invariants the inline block could not:

1. **It can never vote.** Every outcome — classifier exit 2, an unparseable
   payload, a timeout, or a crash inside this script — produces exit code 0.
   The canonical ``pytest`` Golden Replay step remains the sole pass/fail
   authority, and is not referenced, wrapped or re-run here.
2. **It can never echo untrusted text.** Only allowlisted keys are read, and
   each value must match a strict shape or it is replaced by a closed token.

What it deliberately does NOT do
--------------------------------
No regression detection, no tolerance policy, no skip/xfail, no re-run. A
``EXPECTED_SINGLE_FIELD_DELTAS`` observation is recorded as *supplemental
evidence*, never as a successful Golden Replay. Non-exact outcomes stay visible
and distinguishable in the summary.
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from typing import Any, Mapping

#: The classifier module this observer wraps. Invoked in a *fresh* process so the
#: "already-resident" kernel probe reflects a clean interpreter, exactly as it
#: would for anyone running the command by hand.
CLASSIFIER_MODULE = "research.intake.rh04_environment_class"

#: Closed vocabulary: exit code -> coarse classification. Exit 2 deliberately
#: covers several verdicts, which is why the fine-grained `field_verdict` and
#: `environment_verdict` are recorded alongside it rather than replaced by it.
EXIT_CLASSIFICATIONS: Mapping[int, str] = {
    0: "EXACT_REPLAY",
    1: "EXPECTED_SINGLE_FIELD_DELTAS",
    2: "NON_EXACT_OR_UNVERIFIED",
}
REFUSED_LABEL = "OBSERVATION_UNAVAILABLE"

#: Verdicts the classifier may report. Anything else is not echoed.
_FIELD_VERDICTS = frozenset(
    {
        "EXACT_REPLAY",
        "EXPECTED_SINGLE_FIELD_DELTAS",
        "UNEXPECTED_DRIFT",
        "INVALID_DIAGNOSTIC",
        "DIAGNOSTIC_REFUSED",
    }
)
_ENVIRONMENT_VERDICTS = frozenset({"VERIFIED_ENVIRONMENT", "UNVERIFIED_ENVIRONMENT"})
_KERNEL_METHODS = frozenset({"rtld_noload", "process_symbol", "unverified"})

#: A resolved OpenBLAS core name (``SkylakeX``, ``Haswell``, ``HASWELL``, ...).
_KERNEL_PATTERN = re.compile(r"^[A-Za-z0-9_]{1,40}$")
#: A release version such as ``1.26.4``.
_VERSION_PATTERN = re.compile(r"^[0-9]+\.[0-9]+\.[0-9]+([A-Za-z0-9.+!-]*)$")
#: A joined major.minor platform token such as glibc ``2.36``.
_PLATFORM_VERSION_PATTERN = re.compile(r"^[0-9]+\.[0-9]+([A-Za-z0-9.+!-]*)$")
#: A frozen case id.
_CASE_ID_PATTERN = re.compile(r"^[a-z0-9_]{1,64}$")
#: A reason token. Reasons are generated by *our own* validator, and every one
#: of them contains at least one ``:`` or ``_`` separator (``case_id:reason``,
#: ``envelope:key:reason``, ``different_field_count``). Requiring a separator
#: rejects opaque free text such as a secret or a base64 blob that happens to be
#: alphanumeric and would otherwise satisfy a looser allowlist.
_REASON_PATTERN = re.compile(r"^(?=.*[:_.])[A-Za-z0-9_.:\[\]]{1,120}$")

#: Emitted in place of a value that fails its allowlist.
REDACTED = "redacted_unexpected_format"

#: Hard cap on the number of reason tokens echoed (defensive; never hit).
_MAX_REASONS = 32

_SUBPROCESS_TIMEOUT_SECONDS = 900


def _token(value: Any, pattern: re.Pattern[str]) -> str | None:
    """Return ``value`` only if it is a string matching ``pattern``."""
    if isinstance(value, str) and pattern.fullmatch(value):
        return value
    return None


def _int_or_none(value: Any) -> int | None:
    """Return a real ``int``, never a ``bool`` (``bool`` is an ``int`` subclass)."""
    return value if isinstance(value, int) and not isinstance(value, bool) else None


def _reason_tokens(values: Any) -> list[str]:
    """Sanitised, sorted, de-duplicated, bounded reason tokens."""
    if not isinstance(values, list):
        return []
    cleaned = {
        _token(item, _REASON_PATTERN) or REDACTED for item in values[:_MAX_REASONS]
    }
    return sorted(cleaned)


def _kernel_block(node: Any) -> dict[str, str | None]:
    """Project one kernel snapshot onto (numpy, scipy, method, method)."""
    if not isinstance(node, Mapping):
        node = {}
    methods = node.get("kernel_identification_method")
    if not isinstance(methods, Mapping):
        methods = {}

    def method(key: str) -> str | None:
        value = methods.get(key)
        return value if value in _KERNEL_METHODS else None

    return {
        "numpy": _token(node.get("numpy_openblas_kernel"), _KERNEL_PATTERN),
        "scipy": _token(node.get("scipy_openblas_kernel"), _KERNEL_PATTERN),
        "numpy_method": method("numpy_openblas_kernel"),
        "scipy_method": method("scipy_openblas_kernel"),
    }


def summarise(
    payload: Any,
    exit_code: int,
    *,
    stdout_parseable: bool = True,
    stderr_present: bool = False,
) -> dict[str, Any]:
    """Reduce a classifier payload to allowlisted, metadata-only evidence.

    Every field here is independently validated; nothing from ``payload`` is
    echoed merely because it was present.

    ``stdout_parseable`` and ``stderr_present`` are *booleans about the child
    process*, not content from it. They are recorded so a human can tell "the
    classifier refused cleanly" from "the classifier produced garbage", without
    the raw text ever being emitted.
    """
    body: Mapping[str, Any] = payload if isinstance(payload, Mapping) else {}

    environment = body.get("environment")
    if not isinstance(environment, Mapping):
        environment = {}

    snapshot = body.get("kernel_snapshot")
    if not isinstance(snapshot, Mapping):
        snapshot = {}

    field_verdict = body.get("field_verdict")
    environment_verdict = body.get("environment_verdict")

    return {
        "exit_code": exit_code,
        "classifier_stdout_parseable": stdout_parseable is True,
        "classifier_stderr_present": stderr_present is True,
        "classification": EXIT_CLASSIFICATIONS.get(exit_code, REFUSED_LABEL),
        "field_verdict": (
            field_verdict if field_verdict in _FIELD_VERDICTS else None
        ),
        "environment_verdict": (
            environment_verdict
            if environment_verdict in _ENVIRONMENT_VERDICTS
            else None
        ),
        "replay_verdict": (
            body.get("replay_verdict")
            if body.get("replay_verdict") in {"EXACT_REPLAY", "MISMATCH_FOUND"}
            else None
        ),
        "cases_checked": _int_or_none(body.get("cases_checked")),
        "cases_differing": _int_or_none(body.get("cases_differing")),
        "differing_case_ids": sorted(
            {
                case_id
                for item in (
                    body.get("differing_case_ids")
                    if isinstance(body.get("differing_case_ids"), list)
                    else []
                )
                if isinstance(item, str) and _CASE_ID_PATTERN.fullmatch(item)
                for case_id in [item]
            }
        ),
        "field_reasons": _reason_tokens(body.get("field_reasons")),
        "environment_reasons": _reason_tokens(body.get("environment_reasons")),
        "version_drift": _reason_tokens(body.get("version_drift")),
        "python": _token(environment.get("python"), _VERSION_PATTERN),
        "numpy_version": _token(environment.get("numpy_version"), _VERSION_PATTERN),
        "scipy_version": _token(environment.get("scipy_version"), _VERSION_PATTERN),
        "sklearn_version": _token(
            environment.get("sklearn_version"), _VERSION_PATTERN
        ),
        "glibc": _token(environment.get("glibc"), _PLATFORM_VERSION_PATTERN),
        "resolved_environment": _kernel_block(environment),
        "pre_replay": _kernel_block(snapshot.get("pre_replay")),
        "post_replay": _kernel_block(snapshot.get("post_replay")),
    }


def _fmt(value: Any) -> str:
    """Render a value for the markdown summary without inventing content."""
    return "`unknown`" if value is None else f"`{value}`"


def _kernel_row(label: str, block: Mapping[str, Any]) -> str:
    return (
        f"| {label} | {_fmt(block.get('numpy'))} | {_fmt(block.get('numpy_method'))} "
        f"| {_fmt(block.get('scipy'))} | {_fmt(block.get('scipy_method'))} |"
    )


def render_summary(summary: Mapping[str, Any]) -> str:
    """Render the redacted markdown block written to the step summary."""
    post = summary["post_replay"]
    pre = summary["pre_replay"]
    resolved = summary["resolved_environment"]

    lines = [
        "### RH-04 environment observation (NON-VOTING)",
        "",
        "> **Supplemental evidence only.** This step records what one runner did; it",
        "> is **not** a pass, **not** an acceptance decision, and **not** a Golden",
        "> Replay success. The canonical `pytest` Golden Replay step remains the sole",
        "> pass/fail authority. `EXPECTED_SINGLE_FIELD_DELTAS` is never a success.",
        "",
        f"- **Classifier exit code:** `{summary['exit_code']}`"
        f" → **{summary['classification']}**",
        f"- **Field verdict:** {_fmt(summary['field_verdict'])}",
        f"- **Environment verdict:** {_fmt(summary['environment_verdict'])}",
        f"- **Cases:** {_fmt(summary['cases_checked'])} checked, "
        f"{_fmt(summary['cases_differing'])} differing",
        f"- **Classifier stdout parseable:** "
        f"`{str(summary['classifier_stdout_parseable']).lower()}`",
        f"- **Classifier stderr present:** "
        f"`{str(summary['classifier_stderr_present']).lower()}`"
        " (text never recorded)",
    ]

    if summary["differing_case_ids"]:
        ids = ", ".join(f"`{case_id}`" for case_id in summary["differing_case_ids"])
        lines.append(f"- **Differing cases:** {ids}")

    for label, key in (
        ("Field reasons", "field_reasons"),
        ("Environment reasons", "environment_reasons"),
        ("Version drift vs pinned", "version_drift"),
    ):
        tokens = summary[key]
        if tokens:
            rendered = ", ".join(f"`{token}`" for token in tokens)
            lines.append(f"- **{label}:** {rendered}")

    lines += [
        "",
        "| Snapshot | NumPy core | method | SciPy core | method |",
        "|---|---|---|---|---|",
        _kernel_row("`pre_replay` (before any replay work)", pre),
        _kernel_row("`post_replay` (after the replay used BLAS)", post),
        _kernel_row("as recorded in `environment`", resolved),
        "",
        f"- **Versions:** Python {_fmt(summary['python'])}, "
        f"NumPy {_fmt(summary['numpy_version'])}, "
        f"SciPy {_fmt(summary['scipy_version'])}, "
        f"scikit-learn {_fmt(summary['sklearn_version'])}, "
        f"glibc {_fmt(summary['glibc'])}",
        "",
        "**Scope.** These are the OpenBLAS objects resident in *this* process at the",
        "moment shown. They are not proof of the kernel used by every later call,",
        "and not an authoritative host identity. Identity is read with",
        "`RTLD_NOLOAD` / process symbols only, so no library copy is loaded.",
        "",
    ]
    return "\n".join(lines)


def _run_classifier(timeout: int = _SUBPROCESS_TIMEOUT_SECONDS) -> tuple[int, str, str]:
    """Run the classifier in a fresh process. Returns ``(exit_code, out, err)``."""
    completed = subprocess.run(
        [sys.executable, "-m", CLASSIFIER_MODULE],
        capture_output=True,
        text=True,
        timeout=timeout,
        # Inherit the pinned threadpool environment; change nothing about it.
        env=dict(os.environ),
    )
    return completed.returncode, completed.stdout, completed.stderr


def _write_summary(text: str) -> None:
    """Append to the Actions step summary, or echo it locally.

    Locally (no ``GITHUB_STEP_SUMMARY``) the block goes to **stderr**, not
    stdout, so that stdout carries exactly one machine-readable object: the
    sanitised summary JSON. That keeps the log stream parseable and keeps every
    human-readable byte on the same stream as the other diagnostics.
    """
    path = os.environ.get("GITHUB_STEP_SUMMARY")
    if path:
        try:
            with open(path, "a", encoding="utf-8") as handle:
                handle.write(text + "\n")
            return
        except OSError:
            # Never let summary-writing failure change the step outcome.
            pass
    print(text, file=sys.stderr)


def main() -> int:
    """Observe, record, and **always** return 0.

    Nothing the child process wrote is ever echoed, on any stream.

    The child's stdout and stderr are treated as untrusted input: a different
    or compromised classifier version could emit arbitrary text, and GitHub
    Actions raw logs are as visible as the step summary. A previous revision
    forwarded both verbatim, which silently bypassed the redaction that the
    summary path enforces. Only values that passed :func:`summarise` are now
    emitted, plus the closed booleans ``classifier_stdout_parseable`` and
    ``classifier_stderr_present``, which describe the child without quoting it.
    """
    try:
        exit_code, stdout, stderr = _run_classifier()

        # Facts about the child, never its text.
        stderr_present = bool(isinstance(stderr, str) and stderr.strip())

        stdout_parseable = True
        try:
            payload = json.loads(stdout)
        except (ValueError, TypeError):
            payload = None
            stdout_parseable = False

        summary = summarise(
            payload,
            exit_code,
            stdout_parseable=stdout_parseable,
            stderr_present=stderr_present,
        )

        # Sanitised, allowlisted evidence only.
        print(json.dumps(summary, indent=2, sort_keys=True))
        print(
            f"RH-04 observation: exit={summary['exit_code']} "
            f"classification={summary['classification']} "
            f"field={summary['field_verdict']} "
            f"environment={summary['environment_verdict']} "
            f"stdout_parseable={summary['classifier_stdout_parseable']} "
            f"stderr_present={summary['classifier_stderr_present']}",
            file=sys.stderr,
        )
        _write_summary(render_summary(summary))
    except Exception as exc:  # noqa: BLE001 - the observer must never vote
        # Only the exception *class name* is recorded, never its message.
        sys.stderr.write(
            "RH-04 observation unavailable "
            f"({type(exc).__name__}); this step is non-voting and exits 0.\n"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
